"""从架构文档生成本地 file:// 原型的提示词展示副本。"""
from pathlib import Path
import argparse
import hashlib
import json
import re

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='只检查展示副本是否与文档一致')
args = parser.parse_args()
prototype = Path(__file__).resolve().parents[1]
system_design = prototype.parents[1]
source_dir = system_design / '03-系统功能架构/AI任务与提示词'
output = prototype / '原型资源/task-prompt-references.js'
assets = {}
for path in sorted(source_dir.glob('*.md')):
    raw = path.read_bytes()
    text = raw.decode('utf-8-sig')
    frontmatter = re.match(r'\A---\n(.*?)\n---\n', text, re.S)
    if not frontmatter:
        raise SystemExit(f'缺少文档元数据：{path.name}')
    fields = dict(re.findall(r'^([a-z_]+):\s*(.+)$', frontmatter[1], re.M))
    required = ['task_id', 'title', 'version', 'status']
    if any(not fields.get(key) for key in required):
        raise SystemExit(f'缺少必要元数据：{path.name}')
    task_id = fields['task_id']
    if not re.fullmatch(r'AI-(?:L\d-)?\d+', task_id) or task_id in assets:
        raise SystemExit(f'无效或重复任务编号：{path.name}')
    section = re.search(r'^## 3\. 提示词正文\s*\n(.*?)(?=^## |\Z)', text, re.M | re.S)
    blocks = re.findall(r'^```text\n(.*?)\n```', section[1], re.M | re.S) if section else []
    if len(blocks) != 1:
        raise SystemExit(f'第3节须恰好包含一个text正文块：{path.name}')
    assets[task_id] = {
        'title': fields['title'], 'version': fields['version'], 'status': fields['status'],
        'sourcePath': str(path.relative_to(system_design)),
        'sourceHref': '../../' + str(path.relative_to(system_design)),
        'sourceSha256': hashlib.sha256(raw).hexdigest(), 'body': blocks[0],
    }
content = ('\'use strict\';\n// Generated by 验证/同步提示词引用.py. Edit the architecture Markdown source.\n'
           + 'const TASK_PROMPT_REFERENCES = ' + json.dumps(assets, ensure_ascii=False, indent=2) + ';\n')
if args.check:
    if not output.exists() or output.read_text(encoding='utf-8') != content:
        raise SystemExit('提示词展示副本未同步，请运行本脚本（不带 --check）')
else:
    output.write_text(content, encoding='utf-8')
print(f'提示词文档引用检查通过：{len(assets)}项' if args.check else f'已同步{len(assets)}项文档引用')
